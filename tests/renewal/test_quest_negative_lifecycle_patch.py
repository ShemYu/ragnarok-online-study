class LiteralRefusals(unittest.TestCase):
    def test_non_bytes_and_wrong_pin(self):
        with self.assertRaises(ValueError) as caught:
            patch.apply_quest_negative_lifecycle_patch("no", b"", b"")
        self.assertEqual(str(caught.exception), "exact-bytes-required")
        with self.assertRaises(ValueError) as caught:
            patch.apply_quest_negative_lifecycle_patch(bytearray(b"abc"), b"", b"")
        self.assertEqual(str(caught.exception), "exact-bytes-required")
        with self.assertRaises(ValueError) as caught:
            patch.apply_quest_negative_lifecycle_patch(b"", b"", b"")
        self.assertEqual(str(caught.exception), "fixed-full-source-pin")

    def test_missing_duplicate_and_already_present_anchors(self):
        edit = (("admitted-404-branch", patch.OLD_THROW, patch.FETCH_BRANCH),)
        with self.assertRaises(ValueError) as caught:
            patch._edits(b"nothing", edit)
        self.assertEqual(str(caught.exception), "closed-literal-count:admitted-404-branch")
        with self.assertRaises(ValueError) as caught:
            patch._edits(patch.OLD_THROW + patch.OLD_THROW, edit)
        self.assertEqual(str(caught.exception), "closed-literal-count:admitted-404-branch")
        with self.assertRaises(ValueError) as caught:
            patch._edits(patch.OLD_THROW + patch.FETCH_BRANCH, edit)
        self.assertEqual(str(caught.exception), "closed-new-literal-absent:admitted-404-branch")

    def test_inverse_role_shape(self):
        with self.assertRaises(ValueError) as caught:
            patch.inverse_quest_negative_lifecycle_patch({"worker": b"a"})
        self.assertEqual(str(caught.exception), "closed-output-roles")


class CarrierTransforms(unittest.TestCase):
    def test_worker_methods_and_branch_roundtrip(self):
        raw = b"PRE\n" + patch.GETHTTP_HEAD + b"MID\n" + patch.OLD_THROW + patch.SUCCESS_TAIL
        patched, spans = patch._edits(raw, patch.WORKER_FIXED)
        self.assertEqual([item["name"] for item in spans], ["insert-drain-methods", "admitted-404-branch"])
        self.assertIn(b"static drainAdmittedOptionalNative404", patched)
        self.assertIn(patch.FETCH_BRANCH, patched)
        self.assertNotIn(patch.OLD_THROW, patched)
        self.assertIn(patch.SUCCESS_TAIL, patched)
        self.assertIn(b'callback(null, "Can\'t get file")', patched)
        self.assertIn(b"FileSystem.saveFile(filename, buffer);", patched)
        restored, _spans = patch._edits(patched, patch.WORKER_FIXED, inverse=True)
        self.assertEqual(restored, raw)

    def test_prefix_literal_roundtrip(self):
        raw = b"HEAD" + patch.PREFIX_OLD + b",\n    hooks:"
        change = (("refresh-prefix-pin", patch.PREFIX_OLD, patch.PREFIX_NEW),)
        patched, _spans = patch._edits(raw, change)
        self.assertIn(patch.PREFIX_NEW, patched)
        self.assertNotIn(patch.PREFIX_OLD, patched)
        restored, _spans = patch._edits(patched, change, inverse=True)
        self.assertEqual(restored, raw)

    def test_proxy_pin_is_the_only_change(self):
        raw = b"BEFORE" + patch.PROXY_PIN_OLD + b"AFTER sock.settimeout(5) NATIVE404"
        changes, new, _pin = patch._proxy_edit(b"not-the-donor-worker")
        self.assertNotEqual(new, patch.PROXY_PIN_OLD)
        patched, spans = patch._edits(raw, changes)
        self.assertEqual([item["name"] for item in spans], ["retarget-worker-pin"])
        self.assertEqual(patched.replace(new, patch.PROXY_PIN_OLD, 1), raw)
        self.assertIn(b"sock.settimeout(5)", patched)
        restored, _spans = patch._edits(patched, changes, inverse=True)
        self.assertEqual(restored, raw)

    def test_controller_literals_roundtrip(self):
        separator = b"\n/*carrier-gap*/\n"
        raw = separator.join(old for _name, old, _new in patch.CONTROLLER_FIXED)
        patched, spans = patch._edits(raw, patch.CONTROLLER_FIXED)
        self.assertEqual(len(spans), 11)
        self.assertIn(b"onControllerSocketError", patched)
        self.assertIn(b"onControllerSocketMessage", patched)
        self.assertIn(b"retainIncompleteChains", patched)
        self.assertIn(b"readDrainWitness", patched)
        self.assertIn(b"ownedShutdownAllowsCompletion", patched)
        restored, _spans = patch._edits(patched, patch.CONTROLLER_FIXED, inverse=True)
        self.assertEqual(restored, raw)


class DonorRoundtrip(unittest.TestCase):
    def test_full_donor_apply_and_inverse(self):
        root = os.environ.get("T10_NEGATIVE_LIFECYCLE_DONORS")
        if not root:
            self.skipTest(
                "T10_NEGATIVE_LIFECYCLE_DONORS is unset; carrier tests already ran; "
                "full donor apply/inverse waits for the guarded harness"
            )
        directory = Path(root)
        originals = {
            "worker": (directory / "worker.source").read_bytes(),
            "controller": (directory / "controller.source").read_bytes(),
            "proxy": (directory / "proxy.source").read_bytes(),
        }
        for role, raw in originals.items():
            self.assertEqual(patch._pin(raw), patch.INPUT_PINS[role])
        result = patch.apply_quest_negative_lifecycle_patch(
            originals["worker"], originals["controller"], originals["proxy"]
        )
        for role, expected in patch.PREDICTIONS.items():
            self.assertEqual(patch._pin(result[role]), expected)
        proof = result["proof"]
        self.assertEqual(proof["schema"], "t10.005.negative-lifecycle-source-patch.v1")
        self.assertFalse(proof["runtime_admitted"])
        self.assertFalse(proof["admission_ready"])
        self.assertTrue(proof["root5_immutable"])
        self.assertFalse(proof["trace_is_grant"])
        self.assertFalse(proof["prior_normal_or_geometry_qualification_covers_changed_worker"])
        self.assertEqual(proof["launcher_join"], "independent-required")
        self.assertEqual(proof["failure_limit_ms"], 5000)
        self.assertEqual(proof["canonical_negative_body_bytes"], 14)
        expected_roles = ["worker"] * 3 + ["controller"] * 11 + ["proxy"]
        self.assertEqual([span["role"] for span in proof["spans"]], expected_roles)
        self.assertEqual(proof["literal_edit_counts"], {"worker": 3, "controller": 11, "proxy": 1})
        self.assertEqual(
            len({(span["role"], span["name"]) for span in proof["spans"]}),
            len(expected_roles),
        )
        progressive_lengths = {role: len(raw) for role, raw in originals.items()}
        for span in proof["spans"]:
            with self.subTest(proof_span=(span["role"], span["name"])):
                self.assertEqual(set(span), {
                    "name", "role", "coordinate_basis", "start", "old_bytes",
                    "new_bytes", "end_exclusive",
                })
                self.assertEqual(span["coordinate_basis"], "role-bytes-before-this-forward-edit")
                self.assertIsInstance(span["name"], str)
                self.assertTrue(span["name"])
                for field in ("start", "old_bytes", "new_bytes", "end_exclusive"):
                    self.assertIs(type(span[field]), int)
                self.assertGreaterEqual(span["start"], 0)
                self.assertGreater(span["old_bytes"], 0)
                self.assertGreater(span["new_bytes"], 0)
                self.assertEqual(span["end_exclusive"], span["start"] + span["old_bytes"])
                self.assertLessEqual(span["end_exclusive"], progressive_lengths[span["role"]])
                progressive_lengths[span["role"]] += span["new_bytes"] - span["old_bytes"]
        self.assertEqual(progressive_lengths, {role: len(result[role]) for role in originals})
        self.assertEqual((proof["prefix"]["bytes"], proof["prefix"]["sha256"]), PREFIX)
        self.assertEqual(hashlib.sha256(result["worker"][:PREFIX[0]]).hexdigest(), PREFIX[1])
        self.assertIn(patch.PREFIX_NEW, result["worker"])
        self.assertNotIn(patch.PREFIX_OLD, result["worker"])
        self.assertIn(patch.SUCCESS_TAIL, result["worker"])
        self.assertNotIn(patch.OLD_THROW, result["worker"])
        new_pin = ("'ThreadEventHandler.js':(%d,'%s')" % patch._pin(result["worker"])).encode()
        self.assertEqual(originals["proxy"].replace(patch.PROXY_PIN_OLD, new_pin, 1), result["proxy"])
        self.assertEqual(
            patch.inverse_quest_negative_lifecycle_patch(result),
            originals,
        )
        # Direct inverse calls must reject changed outputs before normalizing
        # any replacement literal back to its donor. Proof is not authority.
        for role in ("worker", "controller", "proxy"):
            with self.subTest(inverse_tamper=role):
                changed = dict(result)
                changed[role] += b"\n"
                with self.assertRaises(ValueError) as caught:
                    patch.inverse_quest_negative_lifecycle_patch(changed)
                self.assertEqual(str(caught.exception), "fixed-full-source-pin")

        canonical_prefix = ("prefixBytes:%d,prefixSha256:'%s'" % PREFIX).encode()
        self.assertEqual(result["worker"].count(canonical_prefix), 1)
        self.assertEqual(result["proxy"].count(new_pin), 1)
        wrong_digest = ("0" if PREFIX[1][0] != "0" else "1") + PREFIX[1][1:]
        prefix_tampers = (
            ("length", ("prefixBytes:%d,prefixSha256:'%s'" % (PREFIX[0] + 1, PREFIX[1])).encode()),
            ("digest", ("prefixBytes:%d,prefixSha256:'%s'" % (PREFIX[0], wrong_digest)).encode()),
        )
        for name, wrong_prefix in prefix_tampers:
            for retarget_proxy in (False, True):
                with self.subTest(inverse_prefix=name, retarget_proxy=retarget_proxy):
                    changed = dict(result)
                    changed["worker"] = result["worker"].replace(canonical_prefix, wrong_prefix, 1)
                    self.assertNotEqual(changed["worker"], result["worker"])
                    if retarget_proxy:
                        consistent_pin = ("'ThreadEventHandler.js':(%d,'%s')" % (
                            len(changed["worker"]), hashlib.sha256(changed["worker"]).hexdigest(),
                        )).encode()
                        changed["proxy"] = result["proxy"].replace(new_pin, consistent_pin, 1)
                        self.assertNotEqual(changed["proxy"], result["proxy"])
                    with self.assertRaises(ValueError) as caught:
                        patch.inverse_quest_negative_lifecycle_patch(changed)
                    self.assertEqual(str(caught.exception), "fixed-full-source-pin")

        with self.subTest(inverse_tamper="forged-proof-cannot-authorize-body"):
            changed = dict(result)
            changed["worker"] += b"\n"
            changed["proof"] = {
                "runtime_admitted": True,
                "output_pins": {
                    role: {"bytes": len(changed[role]), "sha256": hashlib.sha256(changed[role]).hexdigest()}
                    for role in originals
                },
            }
            with self.assertRaises(ValueError) as caught:
                patch.inverse_quest_negative_lifecycle_patch(changed)
            self.assertEqual(str(caught.exception), "fixed-full-source-pin")

        for role, raw in originals.items():
            self.assertEqual((directory / (role + ".source")).read_bytes(), raw)
            self.assertEqual(patch._pin(result[role]), OUTPUT[role])
        with self.assertRaises(ValueError) as caught:
            patch.apply_quest_negative_lifecycle_patch(
                result["worker"], result["controller"], result["proxy"]
            )
        self.assertEqual(str(caught.exception), "fixed-full-source-pin")


